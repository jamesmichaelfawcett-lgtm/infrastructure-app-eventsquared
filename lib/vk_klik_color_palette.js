/************************************************************************/
function map_colors(colors, map) {
	if(map == 'full') { return; }
	if(map == '64' || map == '32' || map == '16' || map == '8' || map == '4' || map == '2') {
		var mask;
		if (map == '64') { mask = 0xfc; }
		if (map == '32') { mask = 0xf8; }
		if (map == '16') { mask = 0xf0; }
		if (map == '8') { mask = 0xe0; }
		if (map == '4') { mask = 0xc0; }
		if (map == '2') { mask = 0x80; }
		for(var i = 0; i < colors.length; i++) {
			colors[i][0] = colors[i][0] & mask;
			colors[i][1] = colors[i][1] & mask;
			colors[i][2] = colors[i][2] & mask;

			//boost brightness
			// if(map == '2') {
				colors[i][0] = colors[i][0] * Math.floor(256/mask);
				colors[i][1] = colors[i][1] * Math.floor(256/mask);
				colors[i][2] = colors[i][2] * Math.floor(256/mask);				
			// }


		}	
		return;
	}
	
	for(var i = 0; i < colors.length; i++) {
		var distances = [];
		for (var j = 0; j < map.length; j++) {
			var dr = colors[i][0] - map[j][0]; 
			var dg = colors[i][1] - map[j][1]; 
			var db = colors[i][2] - map[j][2]; 

			var distance = Math.sqrt(dr*dr + dg*dg + db*db);
			distances.push(distance);
		} 
		//* find smallest
		var closest = Math.min(...distances);
		var closest_color = distances.indexOf(closest);
		colors[i][0] = map[closest_color][0];
		colors[i][1] = map[closest_color][1];
		colors[i][2] = map[closest_color][2];
	}
}
